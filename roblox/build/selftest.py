#!/usr/bin/env python3
"""
roblox/build/selftest.py -- tests for the require rewriter itself.

The rewriter's job is to never let a require through that Roblox cannot
execute. That guarantee is only worth as much as the evidence for it, so this
builds synthetic project trees in a temp directory and asserts both halves:
what must be rewritten, and what must make the build *fail* rather than emit
something that breaks only inside Studio.

    python3 roblox/build/selftest.py

Touches nothing in the repository -- every fixture lives in a temp directory.
"""

from __future__ import annotations

import io
import json
import shutil
import sys
import tempfile
import contextlib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import build as B  # noqa: E402

PROJECT = {
    "name": "Fixture",
    "tree": {
        "$className": "DataModel",
        "ReplicatedStorage": {
            "$className": "ReplicatedStorage",
            "Shared": {"$path": "dist/shared"},
        },
        "ServerScriptService": {
            "$className": "ServerScriptService",
            "Server": {"$path": {"optional": "dist/server"}},
        },
    },
}

FAILURES: list = []
PASSES = 0


def check(name: str, cond: bool, detail: str = "") -> None:
    global PASSES
    if cond:
        PASSES += 1
    else:
        FAILURES.append(f"{name}: {detail}")


class Fixture:
    """A throwaway roblox/ directory with its own project file."""

    def __init__(self, files: dict):
        self.dir = Path(tempfile.mkdtemp(prefix="stdbuild-selftest-"))
        (self.dir / "default.project.json").write_text(json.dumps(PROJECT), encoding="utf-8")
        for rel, text in files.items():
            p = self.dir / rel
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(text, encoding="utf-8")

    def run(self, *extra: str):
        """-> (exit code, combined output)."""
        argv = ["--project", str(self.dir / "default.project.json"),
                "--no-analyze", *extra]
        out, err = io.StringIO(), io.StringIO()
        with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
            code = B.main(argv)
        return code, out.getvalue() + err.getvalue()

    def emitted(self, rel: str) -> str:
        return (self.dir / "dist" / rel).read_text(encoding="utf-8")

    def close(self) -> None:
        shutil.rmtree(self.dir, ignore_errors=True)


def positive_cases() -> None:
    fx = Fixture({
        "src/shared/Fixed.luau": "return { one = 1 }\n",
        "src/shared/Json.luau": "return {}\n",
        "src/shared/odd name.luau": "return {}\n",
        "src/shared/sim/State.luau":
            '--!strict\n'
            'local Fixed = require("../Fixed")\n'
            'local Odd = require("../odd name")\n'
            'return { Fixed, Odd }\n',
        "src/shared/sim/Waves.luau":
            'local State = require("./State")\n'
            '-- a comment mentioning require("../Fixed") must survive untouched\n'
            '--[[ and require("./State") in a block comment too ]]\n'
            'local doc = [[a long string holding require("../Json")]]\n'
            'local function late()\n'
            '\tlocal ok, mod = pcall(require, "../Json")\n'
            '\treturn ok, mod, doc\n'
            'end\n'
            'return { State = State, late = late }\n',
        "src/server/Runner.luau":
            'local Arena = require("../shared/sim/State")\n'
            'local function late()\n'
            # the value form crossing services: the argument expression itself
            # contains parentheses, which the verifier must not trip over
            '\treturn pcall(require, "../shared/Fixed")\n'
            'end\n'
            'return { Arena, late }\n',
        "src/shared/content.json": '{"a":1}\n',
    })
    try:
        code, out = fx.run()
        check("positive build succeeds", code == 0, out)
        if code != 0:
            return

        state = fx.emitted("shared/sim/State.luau")
        check("sibling-of-parent require",
              "require(script.Parent.Parent.Fixed)" in state, state)
        check("non-identifier instance name is bracket-indexed",
              'require(script.Parent.Parent["odd name"])' in state, state)
        check("--!strict stays on line 1", state.startswith("--!strict\n"), state[:80])
        check("banner emitted", "GENERATED by" in state, state[:200])

        waves = fx.emitted("shared/sim/Waves.luau")
        check("sibling require", "require(script.Parent.State)" in waves, waves)
        check("line comment untouched",
              'comment mentioning require("../Fixed")' in waves, waves)
        check("block comment untouched",
              'require("./State") in a block comment' in waves, waves)
        check("long string untouched",
              'long string holding require("../Json")' in waves, waves)
        check("require passed as a value is rewritten",
              "pcall(require, script.Parent.Parent.Json)" in waves, waves)

        runner = fx.emitted("server/Runner.luau")
        check("cross-service require uses GetService",
              'game:GetService("ReplicatedStorage")' in runner, runner)
        check("cross-service require waits for each step",
              ':WaitForChild("Shared"):WaitForChild("sim"):WaitForChild("State")' in runner,
              runner)

        check("cross-service require in the value form",
              'pcall(require, game:GetService("ReplicatedStorage")'
              ':WaitForChild("Shared"):WaitForChild("Fixed"))' in runner, runner)

        check("non-luau files copied verbatim",
              (fx.dir / "dist" / "shared" / "content.json").read_text() == '{"a":1}\n')

        code, out = fx.run("--verify-only")
        check("verify-only passes on a good tree", code == 0, out)
        code, out = fx.run("--check")
        check("--check reports a fresh tree as up to date", code == 0, out)

        (fx.dir / "src" / "shared" / "Fixed.luau").write_text("return { one = 2 }\n")
        code, out = fx.run("--check")
        check("--check catches a stale dist", code == 1 and "STALE" in out, out)
    finally:
        fx.close()


NEGATIVE = [
    (
        "require naming a module that does not exist",
        {"src/shared/A.luau": 'return require("./Missing")\n'},
        "resolves to no module",
    ),
    (
        "require reaching outside every build root",
        {"src/shared/A.luau": 'return require("../../bench/FixedStub")\n',
         "bench/FixedStub.luau": "return {}\n"},
        "outside every build root",
    ),
    (
        "require built by concatenation",
        {"src/shared/A.luau": 'local n = "B"\nreturn require("./vectors/" .. n)\n'},
        "mixes a relative module path",
    ),
    (
        "require passed as a value with a computed path",
        {"src/shared/A.luau": 'local p = "./B"\nreturn pcall(require, p)\n'},
        "not a string literal",
    ),
    (
        "a path-shaped literal that is not a require",
        {"src/shared/A.luau": 'local p = "../Fixed"\nreturn p\n'},
        "not in a require position",
    ),
    (
        "a non-relative string require",
        {"src/shared/A.luau": 'return require("SomeGlobalName")\n'},
        "not a relative path",
    ),
    (
        "two files claiming one instance path",
        {"src/shared/A.luau": "return {}\n", "src/shared/A.server.luau": "return {}\n"},
        "both become",
    ),
]


def negative_cases() -> None:
    for name, files, expect in NEGATIVE:
        fx = Fixture(files)
        try:
            code, out = fx.run()
            check(f"fails loudly: {name}", code != 0, f"exit {code}: {out}")
            check(f"message explains: {name}", expect in out,
                  f"expected {expect!r} in output, got: {out.strip()}")
        finally:
            fx.close()


def lexer_cases() -> None:
    """The rewriter's correctness rests entirely on the lexer's boundaries."""
    cases = [
        ('local s = "a\\"b"\nlocal t = "../X"\n', ['a"b', "../X"]),
        ("local s = [==[ ]] still inside ]==]\n", [" ]] still inside "]),
        ("--[==[ comment with ]] inside ]==]\nlocal s = 'x'\n", ["x"]),
        ("local t = a[[long]]\n", ["long"]),
        ("local n = 0x1p-3 local s = '.'\n", ["."]),
        ("-- trailing line comment 'not a string'\nlocal s = \"y\"\n", ["y"]),
    ]
    for src, expect in cases:
        got = [str(t.value) for t in B.lex(src) if t.kind == "STRING"]
        check("lexer string boundaries", got == expect, f"{src!r} -> {got!r}")


def main() -> int:
    positive_cases()
    negative_cases()
    lexer_cases()
    if FAILURES:
        print(f"selftest: {PASSES} passed, {len(FAILURES)} FAILED")
        for f in FAILURES:
            print("  FAIL " + f)
        return 1
    print(f"selftest: {PASSES} checks passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
